// Helper to analyze or look up individual word I'rab
function getWordIrab(rawWord, fallbackSentenceIrab) {
    if (!rawWord) return fallbackSentenceIrab;
    const cleaned = rawWord
        .replace(/[\u064B-\u065F\u0670]/g, '')
        .replace(/[.,؟!\/\-()«»:"'؛]/g, '')
        .trim();

    if (!cleaned) return fallbackSentenceIrab;

    if (wordIrabDictionary[cleaned]) {
        return wordIrabDictionary[cleaned];
    }

    if (cleaned.startsWith('ب') && cleaned.length > 3) {
        const nounPart = cleaned.slice(1);
        return `الباء حرف جر، و(${nounPart}) اسم مجرور وعلامة جره الكسرة`;
    }
    if (cleaned.startsWith('لل') && cleaned.length > 3) {
        const nounPart = 'ال' + cleaned.slice(2);
        return `اللام حرف جر، و(${nounPart}) اسم مجرور وعلامة جره الكسرة`;
    }

    const strippedPunct = rawWord.replace(/[.,؟!\/\-()«»:"'؛]/g, '').trim();
    const lastChar = strippedPunct.slice(-1);

    if (lastChar === '\u064F' || lastChar === '\u064C') {
        return "اسم مرفوع وعلامة رفعه الضمة";
    }
    if (lastChar === '\u064E' || lastChar === '\u064B') {
        return "منصوب وعلامة نصبه الفتحة";
    }
    if (lastChar === '\u0650' || lastChar === '\u064D') {
        return "اسم مجرور وعلامة جره الكسرة";
    }
    if (lastChar === '\u0652') {
        return "مبني على السكون (أو مجزوم بالسكون)";
    }

    if (cleaned.startsWith('ال')) {
        return "اسم معرف بـ (ال) — معرب حسب موقعه في الجملة";
    }

    return fallbackSentenceIrab || "كلمة معربة حسب موقعها في الجملة";
}

// Helper to strip Arabic diacritics and punctuation to look up individual word meanings
function getWordMeaning(rawWord, fallbackSentenceMeaning) {
    if (!rawWord) return fallbackSentenceMeaning;
    const cleaned = rawWord
        .replace(/[\u064B-\u065F\u0670]/g, '')
        .replace(/[.,؟!\/\-()«»:"'؛]/g, '')
        .trim();

    if (!cleaned) return fallbackSentenceMeaning;

    if (wordDictionary[cleaned]) {
        return wordDictionary[cleaned];
    }

    if (cleaned.length > 2) {
        const withoutPrefix = cleaned.replace(/^(ب|ل|و|ف)/, '');
        if (wordDictionary[withoutPrefix]) {
            return wordDictionary[withoutPrefix];
        }
        if (cleaned.startsWith('لل')) {
            const withAl = 'ال' + cleaned.slice(2);
            if (wordDictionary[withAl]) return wordDictionary[withAl];
            const withoutAl = cleaned.slice(2);
            if (wordDictionary[withoutAl]) return wordDictionary[withoutAl];
        }
    }

    return fallbackSentenceMeaning;
}

